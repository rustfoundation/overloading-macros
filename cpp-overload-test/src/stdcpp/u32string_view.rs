//! Test that C++ overloads for [std::u32string_view][u32string_view] can be successfully represented in Rust.
//!
//! [u32string_view]: https://en.cppreference.com/cpp/string/basic_string_view
//!
//! Wrapped overloaded names: constructors.
//!
//! The `basic_string_view(nullptr_t) = delete` constructor (C++23) is not wrapped.
//! It exists only to reject `nullptr` at compile time, and Rust raw pointers
//! can't be `nullptr_t`.
//!
//! A C++ `u32string_view` doesn't own its characters, so it dangles if they are freed first.
//! The natural Rust type is `StdU32StringView<'a>`, but `overload!` doesn't accept it: it
//! generates `impl StdU32StringView` from a bare type name.
//! It also drops `unsafe` from overloads, so they can't take raw pointers.
//!
//! Workaround: the constructors take `&'static [CharT]`, so the compiler guarantees the
//! characters outlive the view, with no copying. Hence:
//! - `const char32_t*` + `count` becomes `&[CharT]` + `count`.
//! - A null-terminated `const char32_t*` becomes [`NullTerminated`].
//! - An iterator pair becomes a `&[CharT]` and a `Range<usize>` of offsets into it.
//!
//! ### Limitations
//!
//! Callers can only build a view from static data, such as string-literal constants, constant
//! arrays, or a leaked `Box`. A view of a local array is a compile error. Supporting borrowed
//! data needs generics (and lifetime) support in `overload!`.

#![allow(unused_braces, reason = "Generated by overload! macro")]

use cpp::cpp;
use splat_overload::overload;
use std::ffi::{c_size_t, c_void};
use std::ops::Range;

// C++ header includes
cpp! {{
    #include <string_view>
    #include <span>
    #include <cstddef>
}}

/// A wrapper struct to hold the returned C++ `std::u32string_view` pointer.
///
/// The constructors only accept `'static` characters, so the view never dangles. See the module docs.
///
/// ### Limitations
///
/// `std::basic_string_view<CharT>` is a template, so this wrapper is hardcoded to `char32_t`.
#[cfg_attr(not(test), expect(dead_code, reason = "Only used in tests"))]
pub struct StdU32StringView(*mut c_void);

/// The C++ `char32_t` type is used as `u32` in Rust since it has the same size and alignment.
///
/// ### Limitations
///
/// Rust doesn't have C++'s `char32_t` but `u32` can hold any 32-bit value, so it is used here.
pub type CharT = u32;

/// A slice that contains a zero terminator, standing in for a C++ `const char32_t*` C string.
#[cfg_attr(not(test), expect(dead_code, reason = "Only used in tests"))]
#[derive(Copy, Clone, Debug)]
pub struct NullTerminated<'a>(&'a [CharT]);

#[cfg_attr(not(test), expect(dead_code, reason = "Only used in tests"))]
impl<'a> NullTerminated<'a> {
    /// Returns `None` if `s` has no zero terminator, because C++ would read past the end.
    pub fn new(s: &'a [CharT]) -> Option<NullTerminated<'a>> {
        s.contains(&0).then_some(NullTerminated(s))
    }

    fn as_ptr(&self) -> *const CharT {
        self.0.as_ptr()
    }
}

#[cfg_attr(not(test), expect(dead_code, reason = "Only used in tests"))]
#[allow(
    non_upper_case_globals,
    reason = "Triggered by cpp! macro in rust-analyzer"
)]
impl StdU32StringView {
    fn default() -> StdU32StringView {
        let view = unsafe {
            cpp!([] -> *mut c_void as "std::u32string_view*" {
                return new std::u32string_view();
            })
        };
        StdU32StringView(view)
    }

    fn copy_from(other: &StdU32StringView) -> StdU32StringView {
        let other_ptr = other.0 as *const c_void;
        let view = unsafe {
            cpp!([other_ptr as "const std::u32string_view*"] -> *mut c_void as "std::u32string_view*" {
                return new std::u32string_view(*other_ptr);
            })
        };
        StdU32StringView(view)
    }

    fn from_ptr_and_count(s: &'static [CharT], count: c_size_t) -> StdU32StringView {
        assert!(
            count <= s.len(),
            "count {count} is greater than the slice length {}",
            s.len()
        );
        // An empty Rust slice is guaranteed to have a dangling pointer, see
        // <https://doc.rust-lang.org/std/slice/fn.from_raw_parts.html#safety>
        if s.is_empty() {
            return StdU32StringView::default();
        }
        let ptr = s.as_ptr();
        let view = unsafe {
            cpp!([ptr as "const char32_t*", count as "size_t"] -> *mut c_void as "std::u32string_view*" {
                return new std::u32string_view(ptr, count);
            })
        };
        StdU32StringView(view)
    }

    fn from_null_terminated(s: NullTerminated<'static>) -> StdU32StringView {
        let ptr = s.as_ptr();
        let view = unsafe {
            cpp!([ptr as "const char32_t*"] -> *mut c_void as "std::u32string_view*" {
                return new std::u32string_view(ptr);
            })
        };
        StdU32StringView(view)
    }

    fn from_iterator_pair(s: &'static [CharT], range: Range<usize>) -> StdU32StringView {
        assert!(
            range.start <= range.end && range.end <= s.len(),
            "range {range:?} is not within the slice length {}",
            s.len()
        );
        // An empty Rust slice is guaranteed to have a dangling pointer, see
        // <https://doc.rust-lang.org/std/slice/fn.from_raw_parts.html#safety>
        if s.is_empty() {
            return StdU32StringView::default();
        }
        let sub = &s[range];
        let first = sub.as_ptr();
        let last = unsafe { first.add(sub.len()) };
        let view = unsafe {
            cpp!([first as "const char32_t*", last as "const char32_t*"] -> *mut c_void as "std::u32string_view*" {
                return new std::u32string_view(first, last);
            })
        };
        StdU32StringView(view)
    }

    fn from_range(items: &'static [CharT]) -> StdU32StringView {
        // An empty Rust slice is guaranteed to have a dangling pointer, see
        // <https://doc.rust-lang.org/std/slice/fn.from_raw_parts.html#safety>
        if items.is_empty() {
            return StdU32StringView::default();
        }
        let len = items.len();
        let ptr = items.as_ptr();
        let view = unsafe {
            cpp!([ptr as "const char32_t*", len as "size_t"] -> *mut c_void as "std::u32string_view*" {
                // C++23 range constructor, called with a contiguous range of `char32_t`.
                return new std::u32string_view(std::span<const char32_t>(ptr, len));
            })
        };
        StdU32StringView(view)
    }

    // Non-overloaded accessors, only used to check which constructor was called.

    fn size(&self) -> c_size_t {
        let slf = self.0 as *const c_void;
        unsafe {
            cpp!([slf as "const std::u32string_view*"] -> c_size_t as "size_t" {
                return slf->size();
            })
        }
    }

    fn data(&self) -> *const CharT {
        let slf = self.0 as *const c_void;
        unsafe {
            cpp!([slf as "const std::u32string_view*"] -> *const CharT as "const char32_t*" {
                return slf->data();
            })
        }
    }

    /// The viewed characters.
    fn chars(&self) -> &[CharT] {
        let len = self.size();
        if len == 0 {
            return &[];
        }
        // The view always points at `'static` characters, which are valid for the rest of the program.
        unsafe { std::slice::from_raw_parts(self.data(), len) }
    }
}

overload! {
    impl StdU32StringView {
        /// Construct an empty view.
        pub fn new() -> StdU32StringView {
            StdU32StringView::default()
        }

        /// Construct a view by copying another view. The copy shares the original's characters.
        pub fn new(other: &StdU32StringView) -> StdU32StringView {
            StdU32StringView::copy_from(other)
        }

        /// Construct a view of the first `count` characters of `s`.
        ///
        /// Panics if `count` is greater than `s.len()`.
        ///
        /// ### Limitations
        ///
        /// The C++ constructor takes a `const char32_t*`, and the view doesn't own the characters.
        /// Rust can't accept that soundly, because `overload!` drops `unsafe` and lifetimes, so
        /// this overload takes a `'static` slice that is checked against `count`.
        pub fn new(s: &'static [CharT], count: c_size_t) -> StdU32StringView {
            StdU32StringView::from_ptr_and_count(s, count)
        }

        /// Construct a view of the characters of `s` before its first zero.
        ///
        /// ### Ergonomics
        ///
        /// Callers must wrap the slice with `NullTerminated::new(slice)`, which returns `None`
        /// if there is no terminator. Rust slices aren't null-terminated, so a bare slice can't
        /// select this overload.
        pub fn new(s: NullTerminated<'static>) -> StdU32StringView {
            StdU32StringView::from_null_terminated(s)
        }

        /// Construct a view from the `range` of offsets into `s`.
        ///
        /// Panics if `range` is reversed or ends after `s.len()`.
        ///
        /// ### Limitations
        ///
        /// C++ accepts any `contiguous_iterator` and `sized_sentinel_for` pair. Rust has no
        /// matching trait for iterators across the FFI boundary, and raw pointers can't be
        /// checked, so the pair is expressed as offsets into one slice.
        pub fn new(s: &'static [CharT], range: Range<usize>) -> StdU32StringView {
            StdU32StringView::from_iterator_pair(s, range)
        }

        /// Construct a view from a contiguous range (C++23).
        ///
        /// ### Limitations
        ///
        /// C++ accepts any `contiguous_range` with a matching element type. Only slices of
        /// `char32_t` are supported here.
        ///
        /// ### Ergonomics
        ///
        /// `as_slice()` is required to match the slice overload, as arrays don't
        /// automatically coerce.
        pub fn new(items: &'static [CharT]) -> StdU32StringView {
            StdU32StringView::from_range(items)
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Convert text to `char32_t` values. `\0` in the text becomes a zero character.
    /// The constructors need `'static` characters, so the buffer is leaked.
    fn cs(text: &str) -> &'static [CharT] {
        Box::leak(
            text.chars()
                .map(|c| c as CharT)
                .collect::<Vec<_>>()
                .into_boxed_slice(),
        )
    }

    /// A view of all of `text`.
    fn view(text: &str) -> StdU32StringView {
        StdU32StringView::new(cs(text))
    }

    /// Coerce a constant array reference to a `'static` slice, which overload selection won't do.
    fn st(items: &'static [CharT]) -> &'static [CharT] {
        items
    }

    fn nt(buf: &'static [CharT]) -> NullTerminated<'static> {
        NullTerminated::new(buf).expect("test buffer has a terminator")
    }

    #[test]
    fn constructor_default() {
        let v = StdU32StringView::new();
        assert_eq!(v.size(), 0);
        assert!(v.data().is_null());
        assert!(v.chars().is_empty());
    }

    #[test]
    fn constructor_pointer_and_count() {
        // The count is used, and the embedded terminator is ignored.
        let text = cs("hello\0xy");
        let v = StdU32StringView::new(text, 8);
        assert_eq!(v.chars(), text);

        let prefix = StdU32StringView::new(text, 3);
        assert_eq!(prefix.chars(), cs("hel"));

        assert_eq!(StdU32StringView::new(text, 0).size(), 0);
        assert_eq!(StdU32StringView::new(st(&[]), 0).size(), 0);
    }

    #[test]
    #[should_panic(expected = "greater than the slice length")]
    fn constructor_pointer_and_count_too_long() {
        StdU32StringView::new(cs("ab"), 3);
    }

    #[test]
    fn constructor_null_terminated() {
        // Scans for the terminator, so only "hello".
        let text = cs("hello\0xy");
        let v = StdU32StringView::new(nt(text));
        assert_eq!(v.chars(), cs("hello"));

        // A leading terminator is an empty string.
        assert_eq!(StdU32StringView::new(nt(cs("\0a"))).size(), 0);

        // No terminator: C++ would read past the end, so it can't be constructed.
        assert!(NullTerminated::new(cs("abc")).is_none());
        assert!(NullTerminated::new(st(&[])).is_none());
    }

    #[test]
    fn constructor_iterator_pair() {
        let text = cs("abcdef");

        // A sub-range of offsets, like (begin + 1, begin + 4).
        let mid = StdU32StringView::new(text, 1..4);
        assert_eq!(mid.chars(), cs("bcd"));

        // Full and empty range.
        assert_eq!(StdU32StringView::new(text, 0..6).chars(), text);
        assert_eq!(StdU32StringView::new(text, 0..0).size(), 0);

        // The range may contain zeros.
        let zeros = cs("\0a\0b");
        assert_eq!(StdU32StringView::new(zeros, 0..4).chars(), zeros);
    }

    #[test]
    #[should_panic(expected = "is not within the slice length")]
    fn constructor_iterator_pair_end_out_of_bounds() {
        StdU32StringView::new(cs("abc"), 1..4);
    }

    #[test]
    fn constructor_range() {
        // The whole slice is used, including embedded zeros, emoji and the largest `char32_t`.
        let text: &'static [CharT] = &[0, u32::MAX, '😀' as CharT, 55296]; // 55296 is a surrogate
        let v = StdU32StringView::new(text);
        assert_eq!(v.chars(), text);

        assert_eq!(StdU32StringView::new(st(&[])).size(), 0);
    }

    #[test]
    fn constructor_copy() {
        let original = view("hello");
        let copy = StdU32StringView::new(&original);
        assert_eq!(copy.chars(), original.chars());
        // A C++ copy shares the characters rather than duplicating them.
        assert_eq!(copy.data(), original.data());

        assert_eq!(StdU32StringView::new(&StdU32StringView::new()).size(), 0);
    }

    #[test]
    fn constructors_pick_different_cpp_constructors() {
        // The same slice gives different sizes depending on which C++ constructor ran.
        let text = cs("ab\0cde");
        assert_eq!(StdU32StringView::new(text).size(), 6); // range
        assert_eq!(StdU32StringView::new(nt(text)).size(), 2); // null-terminated
        assert_eq!(StdU32StringView::new(text, 4).size(), 4); // (s, count)
        assert_eq!(StdU32StringView::new(text, 1..3).size(), 2); // (first, last)
    }
}
