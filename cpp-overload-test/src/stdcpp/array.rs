//! Test that C++ overloads for [std::array][array] can be successfully represented in Rust.
//!
//! `std::array` is an aggregate type, so it has no user-declared constructors. Instead, its
//! constructor overloads are aggregate initialization with up to `N` initializers, plus
//! the implicitly declared copy and move constructors.
//!
//! ### Scope
//!
//! The constructors are the only `std::array` overloads that differ by more than `const` or
//! `&`/`&&`. We also wrap two non-member functions as examples of overloads that only differ by
//! `const` or `&`/`&&`, because each one adds something new:
//! - `get` takes the element index as a compile-time template argument
//! - `to_array` overloads on lvalue and rvalue built-in arrays
//!
//! These overloads are skipped because:
//! - `at`, `front`, `back`, `data`, `begin`, `end`, `rbegin`, and `rend` only differ by `const`
//! - `operator[]` and the comparison operators are already possible in Rust
//! - `operator=` have no equivalent in Rust
//! - `fill`, `size`, `swap`, `empty`, and `max_size` are not overloaded
//!
//! [array]: https://en.cppreference.com/cpp/container/array

#![allow(unused_braces, reason = "Generated by overload! macro")]

use cpp::cpp;
use splat_overload::overload;
use std::ffi::c_void;
use std::marker::PhantomData;

// C++ header includes
cpp! {{
    #include <array>
    #include <utility>

    // The `cpp!` macro failed to compile for array type syntax like `int(*)[3]`,
    // so we have to declare the built-in array type here.
    typedef int IntArray3[3];
}}

/// Workaround for missing generic support in the `overload!` macro.
pub type T = std::ffi::c_int;

/// Workaround for missing const generic support in the `overload!` macro.
///
/// ### Limitations
///
/// The C++ type strings in `cpp!` can't refer to this constant, so `3` is hardcoded.
/// Changing this value without changing every `std::array<int, 3>` string will make the Rust
/// and C++ sizes disagree.
pub const N: usize = 3;

/// A wrapper struct to hold the returned C++ `std::array<int, 3>` pointer.
///
/// The size is in the name, because arrays with different sizes are different C++ types.
///
/// ### Limitations
///
/// This struct and the impl should be generic over the element type and the size.
/// The size is a C++ non-type template parameter, which equivalent to a Rust const generic.
/// FIXME: make the `overload!` macro support generics, including const generics.
#[cfg_attr(not(test), expect(dead_code, reason = "Only used in tests"))]
pub struct StdArray3(*mut c_void, PhantomData<[T; N]>);

/// A tag type that carries a compile-time array index, like the `I` in C++ `std::get<I>`.
///
/// ### Workarounds
///
/// The `overload!` macro doesn't support const generics, so `get` can't be generic over the
/// index. Here, each overload takes a different concrete `Index<I>` type.
pub struct Index<const I: usize>;

#[cfg_attr(not(test), expect(dead_code, reason = "Only used in tests"))]
#[allow(
    non_upper_case_globals,
    reason = "Triggered by cpp! macro in rust-analyzer"
)]
impl StdArray3 {
    // Constructors: internal C++ implementations for `new(...)` overloads
    fn value_init() -> StdArray3 {
        let array = unsafe {
            cpp!([] -> *mut c_void as "std::array<int, 3>*" {
                // The braces value-initialize every element in the array.
                // Without them, `int` elements would be left uninitialized.
                return new std::array<int, 3>{};
            })
        };
        StdArray3(array, PhantomData)
    }

    fn from_initializer_list_1(a: T) -> StdArray3 {
        let array = unsafe {
            cpp!([a as "int"] -> *mut c_void as "std::array<int, 3>*" {
                return new std::array<int, 3>{ a };
            })
        };
        StdArray3(array, PhantomData)
    }

    fn from_initializer_list_2(a: T, b: T) -> StdArray3 {
        let array = unsafe {
            cpp!([a as "int", b as "int"] -> *mut c_void as "std::array<int, 3>*" {
                return new std::array<int, 3>{ a, b };
            })
        };
        StdArray3(array, PhantomData)
    }

    fn from_initializer_list_3(a: T, b: T, c: T) -> StdArray3 {
        let array = unsafe {
            cpp!([a as "int", b as "int", c as "int"] -> *mut c_void as "std::array<int, 3>*" {
                return new std::array<int, 3>{ a, b, c };
            })
        };
        StdArray3(array, PhantomData)
    }

    fn copy_from(other: &StdArray3) -> StdArray3 {
        let other = other.0 as *const c_void;
        let array = unsafe {
            cpp!([other as "const std::array<int, 3>*"] -> *mut c_void as "std::array<int, 3>*" {
                return new std::array<int, 3>(*other);
            })
        };
        StdArray3(array, PhantomData)
    }

    fn move_from(other: &mut StdArray3) -> StdArray3 {
        let other: *mut c_void = other.0;
        let array = unsafe {
            cpp!([other as "std::array<int, 3>*"] -> *mut c_void as "std::array<int, 3>*" {
                return new std::array<int, 3>(std::move(*other));
            })
        };
        StdArray3(array, PhantomData)
    }

    // Non-member functions

    // internal C++ implementations for `to_array(...)` overloads
    fn to_array_copy(items: &[T; N]) -> StdArray3 {
        let items: *const [T; N] = items;
        // SAFETY: `items` points to `N` initialized elements that stay borrowed until the C++ call
        // returns, and `N` matches the size of `IntArray3`.
        let array = unsafe {
            cpp!([items as "const IntArray3*"] -> *mut c_void as "std::array<int, 3>*" {
                // `*items` is an lvalue, so this calls the `T(&)[N]` overload.
                return new std::array<int, 3>(std::to_array(*items));
            })
        };
        StdArray3(array, PhantomData)
    }

    fn to_array_move(items: &mut [T; N]) -> StdArray3 {
        let items: *mut [T; N] = items;
        // SAFETY: `items` points to `N` initialized elements that stay mutably borrowed until the
        // C++ call returns, and `N` matches the size of `IntArray3`.
        let array = unsafe {
            cpp!([items as "IntArray3*"] -> *mut c_void as "std::array<int, 3>*" {
                // `std::move(*items)` is an rvalue, hence calls the `T(&&)[N]` overload.
                return new std::array<int, 3>(std::to_array(std::move(*items)));
            })
        };
        StdArray3(array, PhantomData)
    }

    // internal C++ implementations for `get(...)` overloads
    fn get_0_const(&self) -> &T {
        let slf = self.0 as *const c_void;
        let element = unsafe {
            cpp!([slf as "const std::array<int, 3>*"] -> *const T as "const int*" {
                return &std::get<0>(*slf);
            })
        };
        // SAFETY: `element` is valid for as long as `self` is borrowed.
        unsafe { &*element }
    }

    fn get_1_const(&self) -> &T {
        let slf = self.0 as *const c_void;
        let element = unsafe {
            cpp!([slf as "const std::array<int, 3>*"] -> *const T as "const int*" {
                return &std::get<1>(*slf);
            })
        };
        // SAFETY: `element` is valid for as long as `self` is borrowed.
        unsafe { &*element }
    }

    fn get_2_const(&self) -> &T {
        let slf = self.0 as *const c_void;
        let element = unsafe {
            cpp!([slf as "const std::array<int, 3>*"] -> *const T as "const int*" {
                return &std::get<2>(*slf);
            })
        };
        // SAFETY: `element` is valid for as long as `self` is borrowed.
        unsafe { &*element }
    }

    fn get_0_mut(&mut self) -> &mut T {
        let slf: *mut c_void = self.0;
        let element = unsafe {
            cpp!([slf as "std::array<int, 3>*"] -> *mut T as "int*" {
                return &std::get<0>(*slf);
            })
        };
        // SAFETY: `self` is mutably borrowed, so nothing else can access the element
        // while the returned reference exists.
        unsafe { &mut *element }
    }

    fn get_0_move(self) -> T {
        let slf: *mut c_void = self.0;
        unsafe {
            cpp!([slf as "std::array<int, 3>*"] -> T as "int" {
                return std::get<0>(std::move(*slf));
            })
        }
    }

    // Array checks (not overloaded)

    /// Copy every element out of the array, so tests can check the whole array.
    fn contents(&self) -> [T; N] {
        let slf = self.0 as *const c_void;
        let data = unsafe {
            cpp!([slf as "const std::array<int, 3>*"] -> *const T as "const int*" {
                return slf->data();
            })
        };
        // SAFETY: `data()` points to `N` contiguous, initialized `int` elements, having
        // same layout as `[c_int; N]`.
        unsafe { *(data as *const [T; N]) }
    }
}

// Constructors: `new(...)`
overload! {
    impl StdArray3 {
        /// Construct an array with every element value-initialized (zero for `int`).
        ///
        /// ### Limitations
        ///
        /// C++ has two zero-argument forms: `std::array<int, 3> a;` which leaves `int` elements
        /// uninitialized, and `std::array<int, 3> a{};` that sets them to zero. C++ tells them
        /// apart using syntax, not their argument types. We chose value-initialization,
        /// because reading uninitialized elements is undefined behaviour.
        pub fn new() -> StdArray3 {
            StdArray3::value_init()
        }

        /// Construct an array from 1 item, and value-initialize the other elements.
        ///
        /// ### Limitations
        ///
        /// C++ accepts up to `N` initializers and rejects more at compile time. Here,
        /// `new(a, b, c, d)` fails with a missing overload error. A generic implementation
        /// would need a compile-time check that the number of arguments is at most `N`.
        ///
        /// C++ value-initializes the missing elements, which works like a default argument value
        /// for each element. Rust has no default argument values, so each initializer count needs
        /// its own overload.
        ///
        /// These overloads don't clash with any other constructor, because `std::array` doesn't
        /// have `count` or `value` constructors.
        pub fn new(a: T) -> StdArray3 {
            StdArray3::from_initializer_list_1(a)
        }

        /// Construct an array from 2 items, and value-initialize the last element.
        pub fn new(a: T, b: T) -> StdArray3 {
            StdArray3::from_initializer_list_2(a, b)
        }

        /// Construct an array from 3 items.
        pub fn new(a: T, b: T, c: T) -> StdArray3 {
            StdArray3::from_initializer_list_3(a, b, c)
        }

        /// Copy the elements of another array.
        pub fn new(other: &StdArray3) -> StdArray3 {
            StdArray3::copy_from(other)
        }

        /// Move the elements of another array.
        ///
        /// ### Ergonomics
        ///
        /// This takes `&mut` so the caller still has the old array after the move.
        /// That matches C++, but Rust users usually expect a move to give the value away,
        /// which taking the array by value would do.
        ///
        /// ### Limitations
        ///
        /// In C++, moving an `int` copies it and leaves the source unchanged, so the C++
        /// copy and move constructors produce identical arrays, and tests can't tell
        /// which C++ constructor ran.
        pub fn new(other: &mut StdArray3) -> StdArray3 {
            StdArray3::move_from(other)
        }
    }
}

// Non-member functions: `to_array(...)`
overload! {
    /// Create an array by copying the elements of a built-in array.
    ///
    /// ### Limitations
    ///
    /// C++ uses `T(&)[N]` and `T(&&)[N]` to tell lvalue and rvalue arrays apart. Like the move
    /// constructor, the rvalue overload takes `&mut [T; N]`, because the caller still owns the
    /// moved-from array in C++. For `int` elements, copying and moving have the same effect,
    /// meaning tests can't tell which C++ overload was called.
    fn to_array(items: &[T; N]) -> StdArray3 {
        StdArray3::to_array_copy(items)
    }

    /// Create an array by moving the elements of a built-in array.
    fn to_array(items: &mut [T; N]) -> StdArray3 {
        StdArray3::to_array_move(items)
    }
}

// Non-member functions: `get(...)`
overload! {
    /// Get a constant reference to element 0.
    ///
    /// ### Limitations
    ///
    /// C++ `std::get<I>(array)` takes the index as a template argument, so an index that is out of
    /// range is a compile error. Because `overload!` macro doesn't support const generics,
    /// each index uses the `Index<I>` tag type for its own overload.
    ///
    /// These overloads use `&'static` because elided lifetimes fail with
    /// "missing lifetime in associated type" in the code the macro generates, and the macro
    /// doesn't support generic lifetimes.
    fn get(array: &'static StdArray3, _index: Index<0>) -> &'static T {
        array.get_0_const()
    }

    /// Get a constant reference to element 1.
    fn get(array: &'static StdArray3, _index: Index<1>) -> &'static T {
        array.get_1_const()
    }

    /// Get a constant reference to element 2.
    fn get(array: &'static StdArray3, _index: Index<2>) -> &'static T {
        array.get_2_const()
    }

    /// Get a mutable reference to element 0.
    ///
    /// ### Limitations
    ///
    /// Implementing only the mutable and moving overloads for index 0 here, because
    /// every index works the same way. hence is enough to show that the `&`, `&mut`,
    /// and by-value overloads can coexist.
    fn get(array: &'static mut StdArray3, _index: Index<0>) -> &'static mut T {
        array.get_0_mut()
    }

    /// Move element 0 out of the array.
    ///
    /// ### Limitations
    ///
    /// C++ also has a `const T&& get(const std::array&&)` overload but Rust types can't be `const`,
    ///  so a constant rvalue array has the same Rust type as a moved array. That overload
    /// can't be represented separately from this one.
    fn get(array: StdArray3, _index: Index<0>) -> T {
        array.get_0_move()
    }
}

/// These tests show that the correct Rust and C++ overloads are being called.
#[test]
pub fn test_array() {
    // Constructors: `new(...)`
    //
    // Each constructor call produces different contents, so a call that dispatched to the wrong
    // overload would fail its assertion.
    let value_init = StdArray3::new();
    assert_eq!(value_init.contents(), [0, 0, 0]);

    let from_initializer_list = StdArray3::new(7);
    assert_eq!(from_initializer_list.contents(), [7, 0, 0]);
    let from_initializer_list = StdArray3::new(7, 8);
    assert_eq!(from_initializer_list.contents(), [7, 8, 0]);
    let from_initializer_list = StdArray3::new(7, 8, 9);
    assert_eq!(from_initializer_list.contents(), [7, 8, 9]);

    let copied = StdArray3::new(&from_initializer_list);
    assert_eq!(copied.contents(), [7, 8, 9]);
    // Check that the original array is still usable.
    assert_eq!(from_initializer_list.contents(), [7, 8, 9]);

    let mut to_move = StdArray3::new(4, 5, 6);
    let moved = StdArray3::new(&mut to_move);
    assert_eq!(moved.contents(), [4, 5, 6]);
    // Moving `int` elements leaves them unchanged, so the moved-from array still holds them.
    assert_eq!(to_move.contents(), [4, 5, 6]);

    // Non-member functions: `to_array(...)`
    let items: [T; N] = [1, 2, 3];
    let copied_items = to_array(&items);
    assert_eq!(copied_items.contents(), [1, 2, 3]);
    let mut items_to_move: [T; N] = [4, 5, 6];
    let moved_items = to_array(&mut items_to_move);
    assert_eq!(moved_items.contents(), [4, 5, 6]);
    assert_eq!(items_to_move, [4, 5, 6]);

    // Non-member functions: `get(...)`
    //
    // ### Workaround
    //
    // Leak these arrays to get static references to them. This would never work in production.
    let static_ref = |array: StdArray3| -> &'static StdArray3 { &*Box::leak(Box::new(array)) };
    let static_mut = |array: StdArray3| -> &'static mut StdArray3 { Box::leak(Box::new(array)) };

    let get_array = static_ref(StdArray3::new(7, 8, 9));
    assert_eq!(get(get_array, Index::<0>), &7);
    assert_eq!(get(get_array, Index::<1>), &8);
    assert_eq!(get(get_array, Index::<2>), &9);
    assert_eq!(get(static_mut(StdArray3::new(7, 8, 9)), Index::<0>), &mut 7);
    assert_eq!(get(StdArray3::new(7, 8, 9), Index::<0>), 7);
}
