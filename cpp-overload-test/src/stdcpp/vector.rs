    #[test]
    fn move_constructor_transfers_buffer_and_source_can_be_reused() {
        let mut source: StdVector = StdVector::new(&[2 as T, 5, 9][..]);
        let original_object = source.0;
        let original_data = source.data_ptr();
        let moved: StdVector = StdVector::new(&mut source);
        assert_eq!(source.0, original_object);
        assert_ne!(source.0, moved.0);
        assert_eq!(moved.data_ptr(), original_data);
        assert_contents(&moved, &[2, 5, 9]);

        source.assign_repeated(2, -1 as T);
        assert_contents(&source, &[-1, -1]);
        assert_contents(&moved, &[2, 5, 9]);
        drop(source);
        assert_contents(&moved, &[2, 5, 9]);
    }

