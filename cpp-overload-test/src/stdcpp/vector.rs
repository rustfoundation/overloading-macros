        /// Construct an empty vector.
        pub fn new() -> StdVector {
            StdVector::empty()
        }

        /// Construct `count` default-initialized integer elements (zeros).
        ///
        /// ### Ergonomics
        ///
        /// Counts use `c_size_t`; callers can use an explicit argument type to select
        /// this overload.
        pub fn new(count: c_size_t) -> StdVector {
            StdVector::repeat_default(count)
        }

        /// Construct `count` copies of `value`, following C++ argument order.
        ///
        /// ### Ergonomics
        ///
        /// Counts use `c_size_t`, while elements use `T`. Callers can use explicit
        /// argument types to select this overload.
        pub fn new(count: c_size_t, value: T) -> StdVector {
            StdVector::repeat_with(count, value)
        }

        /// Construct a vector containing the single listed element.
        ///
        /// ### Limitations
        ///
        /// Initializer-list overloads support only one, two, or three elements.
        /// They use C++ braced initialization, unlike the slice overload's iterator pair.
        /// If `T` becomes `c_size_t`, the one- and two-element signatures collide with
        /// the count and fill signatures; a distinct wrapper or tag would be needed.
        ///
        /// ### Ergonomics
        ///
        /// Use explicitly typed `T` arguments for listed elements and `c_size_t` for
        /// counts to distinguish initializer-list construction from count and fill.
        pub fn new(a: T) -> StdVector {
            StdVector::from_initializer_list_1(a)
        }

        /// Construct a vector containing two listed elements, in argument order.
        pub fn new(a: T, b: T) -> StdVector {
            StdVector::from_initializer_list_2(a, b)
        }

        /// Construct a vector containing three listed elements, in argument order.
        pub fn new(a: T, b: T, c: T) -> StdVector {
            StdVector::from_initializer_list_3(a, b, c)
        }

        /// Move another vector's contents, leaving its object valid but in an unspecified state.
        pub fn new(other: &mut StdVector) -> StdVector {
            StdVector::move_from(other)
        }

        /// Copy another vector into independently owned storage.
        pub fn new(other: &StdVector) -> StdVector {
            StdVector::copy_from(other)
        }

        /// Construct from the iterator's remaining items using C++23 `std::from_range`.
        ///
        /// ### Limitations
        ///
        /// Eagerly collects items into a temporary Rust `Vec<T>` until the first `None`,
        /// then copies them into the C++ vector through a `std::span<const item_t>`.
        /// The span borrows the temporary buffer only for the duration of construction.
        /// Empty input uses a default-constructed span without accessing the Rust pointer.
        /// This needs extra buffer storage and does not support infinite input.
        /// It exercises a contiguous, sized C++ range, not a single-pass input range.
        /// The existing element-representation, ZST, and C++ exception limitations apply.
        /// Rust collection may fail or the iterator may panic before entering C++.
