//! Check whether C++ `std::vector<int>` overloads can be represented in Rust.
//!
//! ### Limitations
//!
//! This experiment fixes the element type to C++ `int`; it does not test generic overloads.
//!
//! Rust zero-sized element types (ZSTs), such as `()`, are not supported. A nonempty
//! Rust slice of ZSTs has a logical element count but needs no element storage, and
//! pointer offsets do not advance its address. References must still be non-null
//! and suitably aligned. In C++, even an empty class has a nonzero `sizeof`, and its
//! array elements occupy storage. Empty base classes and `[[no_unique_address]]`
//! members can occupy no additional storage, but these exceptions do not make
//! ordinary vector elements zero-sized.
//!
//! The slice constructor passes the Rust element pointer to C++ as `const item_t*`
//! and forms the iterator range from `first` to `first + count`. This requires
//! compatible Rust and C++ element representations and valid backing storage for
//! that range. A Rust ZST slice cannot be reinterpreted as an array of nonzero-sized
//! C++ objects. The local C++ fallback object handles only `count == 0`; a nonempty
//! ZST slice would bypass it. `PhantomData<T>` records ownership but supplies no
//! element storage. Supporting ZSTs would require a separate conversion strategy,
//! rather than simply changing the `T` and `item_t` aliases.
//!
//! See [Rust ZSTs], [Rust Vec guarantees], [C++ object sizes], and [C++ sizeof].
//!
//! Each constructor uses throwing C++ `new` to allocate the vector object, even for an
//! empty vector. Allocation failure is reported by throwing `std::bad_alloc`, rather
//! than returning a null pointer. Allocating the vector's element storage can also
//! throw `std::bad_alloc`. Excessive element counts can cause other exceptions; for
//! example, libc++ throws `std::length_error` when a count exceeds `max_size()`.
//!
//! Neither these constructors nor the wrappers generated by rust-cpp 0.5.11 catch
//! C++ exceptions. The generated Rust declarations use `extern "C"`, which does not
//! permit unwinding. If a C++ exception unwinds across this boundary into Rust, the
//! behavior is undefined; a Rust panic or clean process abort is not guaranteed.
//! These constructors therefore do not safely handle allocation failures.
//!
//! Safe handling would require catching exceptions on the C++ side before they cross
//! the boundary, then returning an explicit error indication or deliberately
//! terminating the process. Using `new (std::nothrow)` alone would not handle exceptions
//! thrown by the vector constructor while allocating element storage.
//!
//! References: [C++ allocation functions], [the default allocator], [libc++ vector],
//! and [Rust FFI unwinding].
//!
//! [C++ allocation functions]: https://eel.is/c++draft/new.delete.single
//! [the default allocator]: https://eel.is/c++draft/allocator.members
//! [libc++ vector]: https://github.com/llvm/llvm-project/blob/main/libcxx/include/__vector/vector.h
//! [Rust FFI unwinding]: https://doc.rust-lang.org/nomicon/ffi.html#ffi-and-unwinding
//! [Rust ZSTs]: https://doc.rust-lang.org/nomicon/exotic-sizes.html#zero-sized-types-zsts
//! [Rust Vec guarantees]: https://doc.rust-lang.org/std/vec/struct.Vec.html#guarantees
//! [C++ object sizes]: https://eel.is/c++draft/intro.object
//! [C++ sizeof]: https://eel.is/c++draft/expr.sizeof

