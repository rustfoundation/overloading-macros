overload! {
    impl StdVector {
        /// Resize to `count` elements, appending zeros when growing.
        ///
        /// ### Limitations
        ///
        /// Both resize overloads retain the existing allocation-exception limitation:
        /// growth can throw, and an exception crossing the `extern "C"` boundary is
        /// undefined behavior. Excessive counts can throw `std::length_error`.
        /// Reallocation invalidates all element pointers, references, and iterators;
        /// shrinking invalidates those referring to erased elements. The past-the-end
        /// iterator is invalidated when the size changes. Shrinking does not reduce
        /// capacity. The wrapper currently exposes no borrowed element references.
        /// See [C++ vector capacity operations](https://eel.is/c++draft/vector.capacity).
        ///
        /// ### Ergonomics
        ///
        /// `count` is the final length, not the number of elements to append.
        /// Argument count distinguishes default growth from growth with a supplied value.
        pub fn resize(&mut self, count: c_size_t) {
            self.resize_default(count);
        }

        /// Resize to `count` elements, appending copies of `value` when growing.
        ///
        /// Existing elements are preserved unless truncated; `value` is unused when
        /// shrinking or retaining the current size. The allocation and invalidation
        /// limitations documented on the default-growth overload also apply here.
        /// The fill value is passed by value in Rust, rather than by C++ const reference.
        pub fn resize(&mut self, count: c_size_t, value: T) {
            self.resize_with(count, value);
        }
    }
}

overload! {
    impl StdVector {
        /// Erase the element at `position` and return the following element's new index.
        ///
        /// The returned index equals the new length when no following element remains.
        ///
        /// ### Panics
        ///
        /// Panics before entering C++ if `position >= len`.
        ///
        /// ### Limitations
        ///
        /// Both erase overloads adapt C++ iterator arguments and results into indices;
        /// they do not exercise passing C++ iterator wrappers across the boundary.
        /// Returned indices describe the vector immediately after deletion and do not
        /// track elements across later mutations. C++ invalidates iterators and references
        /// at or after the erased position. Later elements shift left; capacity is retained.
        /// With the current `int` elements, erase does not allocate or throw. Types with
        /// throwing assignment would require handling exceptions before crossing the FFI
        /// boundary. See [C++ erase](https://eel.is/c++draft/vector.modifiers).
        ///
        /// ### Ergonomics
        ///
        /// Positions are zero-based and checked in release builds as well as debug builds.
        pub fn erase(&mut self, position: c_size_t) -> c_size_t {
            self.erase_one(position)
        }

        /// Erase `[first, last)` and return the following element's new index.
        ///
        /// Empty ranges, including `[len, len)`, are valid. The result equals `first`,
        /// or the new length when deletion reaches the end. The index-adaptation and
        /// invalidation limitations of the single-element overload also apply here.
        ///
        /// ### Panics
        ///
        /// Panics before entering C++ if `first > last` or `last > len`.
        pub fn erase(&mut self, first: c_size_t, last: c_size_t) -> c_size_t {
            self.erase_range(first, last)
        }
    }
}

impl Drop for StdVector {
    fn drop(&mut self) {
        let vector = self.0;
        // Each constructor allocates a distinct vector. The wrapper cannot be copied,
        // and no accessor exposes its pointer, so this deletes it exactly once.
        unsafe {
            cpp!([vector as "std::vector<item_t>*"] {
                delete vector;
            })
        }
    }
}

