    #[test]
    fn copy_constructor_owns_independent_elements() {
        let copied: StdVector = {
            let source: StdVector = StdVector::new(&[2 as T, 5, 9][..]);
            let copied: StdVector = StdVector::new(&source);
            assert_ne!(source.0, copied.0);
            assert_contents(&source, &[2, 5, 9]);
            assert_contents(&copied, &[2, 5, 9]);

            let source_ptr = source.0;
            unsafe {
                cpp!([source_ptr as "std::vector<item_t>*"] {
                    (*source_ptr)[1] = -1;
                })
            };
            assert_contents(&source, &[2, -1, 9]);
            assert_contents(&copied, &[2, 5, 9]);
            copied
        };
        assert_contents(&copied, &[2, 5, 9]);
    }

