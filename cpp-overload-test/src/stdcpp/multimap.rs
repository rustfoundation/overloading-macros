#[test]
fn test_multimap_erase_key() {
    let mut map = StdMultimap::new((1, 10), (1, 20), (2, 30));

    assert_eq!(map.erase(1), 2);
    assert_eq!(map.len(), 1);
    assert_eq!(map.count_key(1), 0);
    assert_eq!(map.count_key(2), 1);
}

#[test]
fn test_multimap_erase_key_range() {
    let entries: &[(K, V)] = &[(1, 10), (1, 11), (2, 20), (3, 30), (4, 40)];
    let mut map = StdMultimap::new(entries);

    // Removes keys 1 and 2, keeps 3 and 4 (last key is excluded).
    assert_eq!(map.erase(1, 3), 3);
    assert_eq!(map.len(), 2);
    assert_eq!(map.count_key(3), 1);
    assert_eq!(map.count_key(4), 1);
}

#[test]
fn test_multimap_erase_empty_or_reversed_range() {
    let mut map = StdMultimap::new((1, 10), (2, 20));

    assert_eq!(map.erase(2, 2), 0);
    assert_eq!(map.erase(3, 1), 0);
    assert_eq!(map.len(), 2);
}

#[test]
fn test_multimap_erase_iterator() {
    let mut map = StdMultimap::new((1, 10), (1, 20), (2, 30));

    let pos = map.lower_bound(1);
    map.erase(&pos);

    // Unlike `erase(key)`, this removes only one of the duplicates.
    assert_eq!(map.len(), 2);
    assert_eq!(map.count_key(1), 1);
    assert_eq!(map.count_key(2), 1);
}

#[test]
fn test_multimap_erase_end_iterator() {
    let mut map = StdMultimap::new((1, 10), (2, 20));

    let end = map.lower_bound(99); // past every key, so this is `end()`
    map.erase(&end);

    assert_eq!(map.len(), 2);
}

#[test]
fn test_multimap_merge() {
    let mut a = StdMultimap::new((1, 10), (2, 20));
    let mut b = StdMultimap::new((1, 11), (3, 30));

    a.merge(&mut b);

    assert_eq!(a.len(), 4);
    assert_eq!(a.count_key(1), 2);
    assert_eq!(a.count_key(2), 1);
    assert_eq!(a.count_key(3), 1);
    assert!(b.is_empty());
}
