//! Test that C++ overloads for [std::multimap][multimap] can be successfully represented in Rust.
//!
//! [multimap]: https://en.cppreference.com/w/cpp/container/multimap
//! [multimap.rs]: https://github.com/rustfoundation/overloading-macros/blob/main/cpp-overload-test/src/stdcpp/multimap.rs
//!
//! Overloaded method names wrapped here:
//! - `new`: default, move, slice of pairs, and one, two or three pairs
//! - `insert`: `(key, value)`, `(hint_key, key, value)`, and `(&[(K, V)])`
//! - `erase`: `(key)`, `(first_key, last_key)`, `(&StdMultimapIter)`
//! - `merge`: `(&mut StdMultimap)`
//!
//! # Limitations
//!
//! - The wrapper uses `c_int` for both keys and values because the `overload!` macro
//!   does not currently support generics.
//!
//! ## Not wrapped
//!
//! Skipped by task rules:
//!
//! - Overloads that only add an allocator argument.
//! - `operator=` and `swap`, because Rust has no equivalent.
//! - `insert(value_type&&)` and `insert(hint, value_type&&)`: differ from the `const&`
//!   versions only by `&&`.
//!
//! Constructors (`new`):
//! - Copy constructor `multimap(const multimap&)`: differs from the wrapped move constructor
//!   only by `const&` vs `&&`, so one example is enough.
//! - Compare constructor - `Compare` is a type parameter, and the wrapper is fixed to `std::multimap<int, int>`.
//! - C++ iterator-range constructor (first, last) - slice constructor covers the idea
//! - std::from_range (C++23) - depends on C++23 library support
//!
//! (`insert`):
//! - `insert(P&&)` - has no Rust equivalent
//! - `insert(node_type&&)` and `insert(hint, node_type&&)` - node handles come from extracting nodes, which is not yet wrapped
//! - `insert(initializer_list)` and `insert(first, last)` - implemented as `insert(&[(K, V)])`(slice overload)
//!
//! (`erase`):
//! - `erase(iterator pos)`: have been covered by `erase(const_iterator pos)` - differs by const
//! - `erase(first, last)` with C++ iterators: approximated by `erase(first_key, last_key)`.
//! - `erase(K&& x)`: the wrapper uses a fixed `int` key type, and the key-based
//!   `erase(const key_type& key)` overload already covers the main erasure behaviour.
//!
//! (`merge`):
//! - `merge(std::map<..., C2>&)` and `merge(std::map<..., C2>&&)`: need a `std::map`
//!   wrapper type, which does not exist here.
//! - `merge(std::multimap<..., C2>&&)`: differs from the wrapped `merge(std::multimap<..., C2>&)` by `&&`.
//! - Source maps with a comparator other than `std::less<int>`: the macro cannot
//!   express the `C2` type parameter.

#![allow(unused_braces, reason = "Generated by overload! macro")]

use cpp::cpp;
use splat_overload::overload;
use std::ffi::{c_char, c_size_t, c_void};
use std::marker::PhantomData;

cpp! {{
    #include <map>
    #include <initializer_list>
    #include <cstddef>
    #include <vector>
}}

/// Workaround for missing generic support in the `overload!` macro.
pub type K = std::ffi::c_int;
pub type V = std::ffi::c_int;

/// A wrapper struct to hold the returned C++ `std::multimap<int, int>` pointer.
///
/// ### Limitations
///
/// This struct and the impl should be fully generic over the key and value types.
/// FIXME: make the `overload!` macro support generics.
pub struct StdMultimap(*mut c_void, PhantomData<(K, V)>);

/// A wrapper struct to hold a C++ `std::multimap<int, int>::const_iterator` object.
///
/// ### Limitations
///
/// The iterator is not tied to the map's lifetime. A borrowing iterator would stop
/// `map.erase(&pos)` from compiling, because `erase` needs `&mut map` while the iterator
/// still borrows the map.
#[cfg_attr(not(test), expect(dead_code, reason = "Only used in tests"))]
pub struct StdMultimapIter(*mut c_void, PhantomData<(K, V)>);

#[cfg_attr(not(test), expect(dead_code, reason = "Only used in tests"))]
#[allow(
    non_upper_case_globals,
    reason = "Triggered by cpp! macro in rust-analyzer"
)]
// The cpp! macro doesn't work inside the overload! macro, so we extract C++ calls into separate methods.
// A mature overload feature (or a production C++ project) wouldn't need this impl block.
impl StdMultimap {
    // Create an empty C++ std::multimap.
    // not overloaded, but used to implement the default constructor.
    fn default() -> StdMultimap {
        let map = unsafe {
            cpp!([] -> *mut c_void as "std::multimap<int, int>*" {
                return new std::multimap<int, int>();
            })
        };

        StdMultimap(map, PhantomData)
    }

    // Returns the number of key-value pairs.
    // not overloaded, but used to check that the multimap is working correctly.
    fn len(&self) -> c_size_t {
        let map = self.0 as *const c_void;

        unsafe {
            cpp!([map as "const std::multimap<int, int>*"]
                -> c_size_t as "size_t" {
                return map->size();
            })
        }
    }

    // not overloaded, but used to check that the multimap is working correctly.
    fn is_empty(&self) -> bool {
        let map = self.0 as *const c_void;

        let empty = unsafe {
            cpp!([map as "const std::multimap<int, int>*"] -> c_char as "char" {
                // `char` is FFI-safe, but Rust `bool` is not.
                // C++ automatically promotes `bool` to `char`.
                return map->empty();
            })
        };

        empty != 0
    }

    // Construct a multimap from a single key-value pair.
    fn from_initializer_list_1(a: (K, V)) -> StdMultimap {
        let (ak, av) = a;
        let map = unsafe {
            cpp!([ak as "int", av as "int"] -> *mut c_void as "std::multimap<int, int>*" {
                return new std::multimap<int, int>{ {ak, av} };
            })
        };
        StdMultimap(map, PhantomData)
    }

    fn from_initializer_list_2(a: (K, V), b: (K, V)) -> StdMultimap {
        let (ak, av) = a;
        let (bk, bv) = b;

        let map = unsafe {
            cpp!([
                ak as "int", av as "int", bk as "int", bv as "int"] -> *mut c_void as "std::multimap<int, int>*" {
                return new std::multimap<int, int>{{ak, av},{bk, bv} };
            })
        };

        StdMultimap(map, PhantomData)
    }

    fn from_initializer_list_3(a: (K, V), b: (K, V), c: (K, V)) -> StdMultimap {
        let (ak, av) = a;
        let (bk, bv) = b;
        let (ck, cv) = c;

        let map = unsafe {
            cpp!([
                ak as "int", av as "int",
                bk as "int", bv as "int",
                ck as "int", cv as "int"
            ] -> *mut c_void as "std::multimap<int, int>*" {
                return new std::multimap<int, int>{
                    {ak, av},
                    {bk, bv},
                    {ck, cv}
                };
            })
        };

        StdMultimap(map, PhantomData)
    }

    // Number of elements with this key (not overloaded, used to check duplicates are kept).
    fn count_key(&self, key: K) -> c_size_t {
        let slf = self.0 as *const c_void;
        unsafe {
            cpp!([slf as "const std::multimap<int, int>*", key as "int"] -> c_size_t as "size_t" {
                return slf->count(key);
            })
        }
    }

    // Not overloaded, but used to get an iterator to pass to `erase(pos)`.
    // Returns an iterator to the first element with a key >= `key`, or `end()`.
    fn lower_bound(&self, key: K) -> StdMultimapIter {
        let map = self.0 as *const c_void;
        let iter = unsafe {
            // FIXME: is the returned type always a pointer type?
            cpp!([map as "const std::multimap<int, int>*", key as "int"]
                -> *mut c_void as "std::multimap<int, int>::const_iterator" {
                return map->lower_bound(key);
            })
        };
        StdMultimapIter(iter, PhantomData)
    }

    // Construct a new multimap by moving from another multimap.
    fn move_from(other: &mut StdMultimap) -> StdMultimap {
        let other_map = other.0;

        let map = unsafe {
            cpp!([other_map as "std::multimap<int, int>*"]
                -> *mut c_void as "std::multimap<int, int>*" {
                return new std::multimap<int, int>(std::move(*other_map));
            })
        };

        StdMultimap(map, PhantomData)
    }

    fn from_slice(entries: &[(K, V)]) -> StdMultimap {
        // An empty Rust slice has a dangling pointer, see
        // <https://doc.rust-lang.org/std/slice/fn.from_raw_parts.html#safety>
        if entries.is_empty() {
            return StdMultimap::default();
        }

        // Rust tuples are not assumed to have the same layout as C++ pairs.
        // Split the entries into separate arrays for the FFI boundary.
        let keys: Vec<K> = entries.iter().map(|(key, _)| *key).collect();
        let values: Vec<V> = entries.iter().map(|(_, value)| *value).collect();

        let keys_ptr = keys.as_ptr();
        let values_ptr = values.as_ptr();
        let count = entries.len();

        // SAFETY: both pointers are non-null and point to `count` initialized ints.
        // `keys` and `values` stay alive until after the C++ call returns.
        let map = unsafe {
            cpp!([
                keys_ptr as "const int*",
                values_ptr as "const int*",
                count as "size_t"
            ] -> *mut c_void as "std::multimap<int, int>*" {
                std::vector<std::pair<int, int>> pairs;
                pairs.reserve(count); // avoids repeated reallocation

                for (size_t i = 0; i < count; ++i) {
                    pairs.emplace_back(keys_ptr[i], values_ptr[i]);
                }

                return new std::multimap<int, int>(
                    pairs.begin(),
                    pairs.end()
                );
            })
        };

        StdMultimap(map, PhantomData)
    }

    // Insert one key-value pair (the C++ `insert(value)` overload).
    fn insert_internal(&mut self, key: K, value: V) {
        let map = self.0;

        // SAFETY: `map` is a valid pointer to a live `std::multimap<int, int>`, owned by
        // `self`, and `&mut self` guarantees no other access during the call.
        unsafe {
            cpp!([
                map as "std::multimap<int, int>*",
                key as "int",
                value as "int"
            ] {
                map->insert({key, value});
            })
        }
    }

    // Insert one key-value pair, using the position found by `lower_bound(hint_key)`
    // as the hint (the C++ `insert(hint, value)` overload).
    fn insert_with_hint_internal(&mut self, hint_key: K, key: K, value: V) {
        let map = self.0;

        // SAFETY: `map` is a valid pointer to a live `std::multimap<int, int>`, owned by
        // `self`, and `&mut self` guarantees no other access during the call.
        unsafe {
            cpp!([
                map as "std::multimap<int, int>*",
                hint_key as "int",
                key as "int",
                value as "int"
            ] {
                auto hint = map->lower_bound(hint_key);
                map->insert(hint, {key, value});
            })
        }
    }

    // Insert every pair from a slice `insert(first, last)` and
    // `insert(initializer_list)` overloads.
    fn insert_slice_internal(&mut self, entries: &[(K, V)]) {
        // Inserting an empty slice should leave the map unchanged.
        if entries.is_empty() {
            return;
        }

        // Rust tuples are not assumed to have the same layout as C++ pairs.
        let keys: Vec<K> = entries.iter().map(|(key, _)| *key).collect();
        let values: Vec<V> = entries.iter().map(|(_, value)| *value).collect();

        let keys_ptr = keys.as_ptr();
        let values_ptr = values.as_ptr();
        let count = entries.len();
        let map_ptr = self.0;

        // SAFETY: both pointers point to `count` initialized ints, and `keys` and
        // `values` stay alive until the C++ call returns. `map_ptr` is a valid pointer
        // owned by `self`, and `&mut self` guarantees no other access.
        unsafe {
            cpp!([
                map_ptr as "std::multimap<int, int>*",
                keys_ptr as "const int*",
                values_ptr as "const int*",
                count as "size_t"
            ] {
                for (size_t i = 0; i < count; ++i) {
                    map_ptr->insert({keys_ptr[i], values_ptr[i]});
                }
            })
        }
    }

    // Erase every element with this key (the C++ `erase(const key_type&)` overload).
    fn erase_key_internal(&mut self, key: K) -> c_size_t {
        let map = self.0;

        // SAFETY: `map` is a valid pointer owned by `self`, and `&mut self`
        // guarantees no other access during the call.
        unsafe {
            cpp!([map as "std::multimap<int, int>*", key as "int"] -> c_size_t as "size_t" {
                return map->erase(key);
            })
        }
    }

    // Erase every element with a key in [first_key, last_key) (the C++ `erase(first, last)` overload).
    fn erase_range_internal(&mut self, first_key: K, last_key: K) -> c_size_t {
        let map = self.0;

        // SAFETY: `map` is a valid pointer owned by `self`, and `&mut self`
        // guarantees no other access during the call.
        unsafe {
            cpp!([
                map as "std::multimap<int, int>*",
                first_key as "int",
                last_key as "int"
            ] -> c_size_t as "size_t" {
                if (last_key <= first_key) {
                    return 0;
                }
                auto first = map->lower_bound(first_key);
                auto last = map->lower_bound(last_key);
                size_t removed = std::distance(first, last);
                map->erase(first, last);
                return removed;
            })
        }
    }

    // Erase the element at `pos` (the C++ `erase(const_iterator)` overload).
    fn erase_pos_internal(&mut self, pos: &StdMultimapIter) {
        let map = self.0;
        let pos = pos.0 as *const c_void;

        // SAFETY: `map` is a valid pointer owned by `self`, and `&mut self` guarantees no
        // other access during the call. Erasing `end()` is undefined behaviour in C++, so
        // it is checked first. `pos` must come from this map and must not be invalidated.
        unsafe {
            cpp!([
                map as "std::multimap<int, int>*",
                pos as "std::multimap<int, int>::const_iterator"
            ] {
                if (pos != map->cend()) {
                    map->erase(pos);
                }
            })
        }
    }

    // Move all elements from `other` into this multimap (the C++ `merge(multimap&)` overload).
    fn merge_internal(&mut self, other: &mut StdMultimap) {
        let map = self.0;
        let other_map = other.0;

        // SAFETY: both pointers are valid, live multimaps. `&mut self` and `&mut other`
        // cannot alias, so they are distinct maps, as `merge` requires.
        unsafe {
            cpp!([
                map as "std::multimap<int, int>*",
                other_map as "std::multimap<int, int>*"
            ] {
                map->merge(*other_map);
            })
        }
    }
}

// We ignore constructors that only differ by an allocator argument, because they're not interesting overloads to test.
overload! {
    impl StdMultimap {
        /// Construct an empty multimap.
        pub fn new() -> StdMultimap {
            StdMultimap::default()
        }

        /// Move-construct - a multimap from a mutable multimap reference.
        ///
        /// The contents of `other` are moved into the new map, leaving `other` in a valid
        /// but unspecified state.
        ///
        /// ### Limitations
        ///
        /// C++ also has a copy constructor, `multimap(const multimap&)`, which differs only
        /// by `const&` vs `&&`, so only the move form is wrapped.
        ///
        /// ### Ergonomics
        ///
        /// Rust moves by value, so taking `&mut` and leaving the source usable is unusual
        /// and may surprise callers.
        pub fn new(other: &mut StdMultimap) -> StdMultimap {
            StdMultimap::move_from(other)
        }

        /// Construct a multimap from a slice of key-value pairs.
        ///
        /// ### Limitations
        ///
        /// Rust tuples are not FFI-safe, so the pairs are split into separate key and value
        /// arrays and rebuilt as C++ pairs. This costs extra copies. It also mirrors the C++
        /// iterator-range constructor, but takes a Rust slice rather than C++ iterators.
        pub fn new(entries: &[(K, V)]) -> StdMultimap {
            StdMultimap::from_slice(entries)
        }

        /// Construct a multimap from the supplied key-value pairs.
        ///
        /// Each argument represents one `(key, value)` pair. The resulting
        /// multimap contains all supplied pairs, including pairs with duplicate keys.
        ///
        /// ### Limitations
        ///
        /// This is just an example; a production implementation would support
        /// any number of key-value pairs.
        ///
        /// Rust doesn't have a language equivalent to C++'s `std::initializer_list`,
        /// and it doesn't have variadic tuples, so we provide separate constructors for
        /// one, two, and three key-value pairs instead of a single constructor that
        /// accepts any number of pairs.
        ///
        /// These overloads do not clash with the other `new` overloads. Each pair is a
        /// tuple `(K, V)`, which is a different type from `&StdMultimap` and `&[(K, V)]`.
        ///
        /// These examples use fixed-size tuples for key-value pairs because the
        /// current wrapper uses `c_int` for both keys and values. The underlying
        /// C++ type and FFI conversions are defined for `std::multimap<int, int>`.
        ///
        /// ### Ergonomics
        ///
        /// Each key-value pair must be passed as a tuple. For example, constructing a multimap with
        /// one pair requires `StdMultimap::new((1, 10))`, while multiple pairs can be passed as
        /// `StdMultimap::new((1, 10), (2, 20))`.
        /// The double parentheses can make the syntax confusing, especially
        /// for users who might expect to pass the key and value as separate
        /// arguments, such as `StdMultimap::new(1, 10)`.
        pub fn new(a: (K, V)) -> StdMultimap {
            StdMultimap::from_initializer_list_1(a)
        }

        pub fn new(a: (K, V), b: (K, V)) -> StdMultimap {
            StdMultimap::from_initializer_list_2(a, b)
        }

        pub fn new(a: (K, V), b: (K, V), c: (K, V)) -> StdMultimap {
            StdMultimap::from_initializer_list_3(a, b, c)
        }
    }

}

overload! {
    impl StdMultimap {
        /// Insert a key-value pair into the multimap.
        /// Duplicate keys are kept.
        ///
        /// ### Limitations
        ///
        /// C++ `insert(value)` returns an iterator to the inserted element. This wrapper
        /// returns nothing, because the wrapper does not return iterators. Callers can use
        /// `count_key` to check the result instead.
        ///
        /// C++ also takes a single `std::pair<const int, int>`, but Rust tuples are not
        /// FFI-safe, so this overload takes the key and value as two separate arguments.
        ///
        /// ### Ergonomics
        ///
        /// `insert(1, 10)` and the hint overload `insert(0, 1, 10)` differ only in
        /// argument count, so it is easy to mix up which number is the key, the value, or
        /// the hint.
        pub fn insert(&mut self, key: K, value: V) {
            self.insert_internal(key, value);
        }

        /// Insert a key-value pair, using the position of `hint_key` as a placement hint.
        ///
        /// ### Limitations
        ///
        /// C++ takes an iterator as the hint. This wrapper takes a key and calls
        /// `lower_bound` to produce the iterator, so callers cannot pass an arbitrary
        /// iterator. The return iterator is also dropped, as above.
        ///
        /// ### Ergonomics
        ///
        /// The hint is only a performance hint. A wrong `hint_key` never changes which elements
        /// are stored, but can change order for equal keys.
        pub fn insert(&mut self, hint_key: K, key: K, value: V) {
            self.insert_with_hint_internal(hint_key, key, value)
        }

        /// Insert every key-value pair from a slice. Duplicate keys are kept.
        ///
        /// ### Limitations
        ///
        /// This one overload stands in for two C++ overloads: `insert(first, last)` and
        /// `insert(initializer_list)`. Rust has no `initializer_list`, and a slice covers the
        /// same use. It takes a Rust slice, not C++ iterators, so a range from another C++
        /// container can't be passed in.
        ///
        /// Rust tuples are not FFI-safe, so the pairs are split into two arrays first, which
        /// costs extra copies.
        ///
        /// ### Ergonomics
        ///
        /// An array needs a slice conversion, or a typed variable first, for example
        /// `let entries: &[(K, V)] = &[(1, 10)];`.
        pub fn insert(&mut self, entries: &[(K, V)]) {
            self.insert_slice_internal(entries)
        }
    }
}

overload! {
    impl StdMultimap {
        /// Erase every element whose key equals `key`.
        /// Returns the number of elements removed.
        ///
        /// Unlike a normal map, a multimap can hold several elements per key, so
        /// removes all of them, not just one.
        ///
        /// ### Ergonomics
        ///
        /// `erase(key)` and `erase(first_key, last_key)` differ only in argument count,
        /// so it is easy to confuse a single key with the start of a range.
        pub fn erase(&mut self, key: K) -> c_size_t {
            self.erase_key_internal(key)
        }

        /// Erase every element with a key in `[first_key, last_key)`.
        /// Returns the number of elements removed.
        ///
        /// ### Limitations
        ///
        /// C++ takes two iterators and returns an iterator to the element after the
        /// erased range. This wrapper takes two keys, finds the iterators with
        /// `lower_bound`, and returns the number of elements removed instead.
        pub fn erase(&mut self, first_key: K, last_key: K) -> c_size_t {
            self.erase_range_internal(first_key, last_key)
        }

        /// Erase the element at `pos`.
        ///
        /// Unlike `erase(key)`, this removes exactly one element, even if the key has
        /// duplicates.
        ///
        /// ### Limitations
        ///
        /// C++ also has `erase(iterator)`, which differs only by iterator constness, so
        /// only `erase(const_iterator)` is wrapped.
        ///
        /// The iterator is not tied to the map's lifetime, so using `pos` after the map
        /// is modified is undefined behaviour.
        ///
        /// ### Ergonomics
        ///
        /// This does not clash with `erase(key: K)`, because `&StdMultimapIter` is a
        /// different type from `K`.
        pub fn erase(&mut self, pos: &StdMultimapIter) {
            self.erase_pos_internal(pos)
        }
    }
}

overload! {
    impl StdMultimap {
        /// Move all elements from `other` into this multimap.
        ///
        /// Elements are moved, not copied. A multimap accepts duplicate keys, so every
        /// element moves and `other` is empty afterwards.
        ///
        /// ### Limitations
        ///
        /// C++ is a template over the source's comparator type `C2`. The wrapper is fixed
        /// to `std::multimap<int, int>`, so only the same comparator is supported.
        ///
        /// ### Ergonomics
        ///
        /// Merging a map into itself is impossible, because `&mut self` and `&mut other`
        /// cannot alias.
        pub fn merge(&mut self, other: &mut StdMultimap) {
            self.merge_internal(other)
        }
    }
}

// The C++ multimap is deleted when the Rust wrapper is dropped.
impl Drop for StdMultimap {
    fn drop(&mut self) {
        let map = self.0;
        // SAFETY: `map` was created by `new` in this wrapper, is deleted only here, and
        // `self` is being dropped, so it cannot be used afterwards

        unsafe {
            cpp!([map as "std::multimap<int, int>*"] {
                delete map;
            })
        }
    }
}

// These tests show that the correct Rust and C++ overloads are being called.
#[test]
fn test_multimap() {
    let default_map = StdMultimap::new();
    assert!(default_map.is_empty());
    assert_eq!(default_map.len(), 0);

    let one = StdMultimap::new((1, 10));
    assert_eq!(one.len(), 1);
    assert_eq!(one.count_key(1), 1);
}

#[test]
fn test_multimap_initializer_list_two_pairs() {
    let map = StdMultimap::new((2, 20), (1, 10));

    assert_eq!(map.len(), 2);
    assert_eq!(map.count_key(1), 1);
    assert_eq!(map.count_key(2), 1);
}

#[test]
fn test_multimap_initializer_list_three_pairs() {
    let map = StdMultimap::new((1, 10), (1, 20), (2, 30));

    assert_eq!(map.len(), 3);
    assert_eq!(map.count_key(1), 2);
    assert_eq!(map.count_key(2), 1);
}

#[test]
fn test_multimap_move_constructor() {
    let mut original = StdMultimap::new((1, 10), (1, 20));

    let moved = StdMultimap::new(&mut original);

    assert_eq!(moved.len(), 2);
    assert_eq!(moved.count_key(1), 2);

    let _ = original.len();
    original.insert(5, 50);
    assert_eq!(original.count_key(5), 1);
}

